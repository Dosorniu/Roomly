import assert from 'node:assert/strict';
import { createSeed, rooms } from '../data/catalog';
import { applyCommand, expire, viewRoom, FREE_FRESHNESS_MS } from '../services/domain';
const now=1000000;let state=createSeed(now);const room=rooms.find(r=>r.id==='112')!;
const run=(cmd:any,t=now)=>{state=applyCommand(state,rooms,cmd,t,'session-'+state.revision);};
run({type:'checkIn',roomId:room.id,userId:'A',minutes:60,openToShare:true});
assert.equal(viewRoom(state,room,now).status,'share');
assert.throws(()=>run({type:'checkIn',roomId:room.id,userId:'B',minutes:30,openToShare:true}));
run({type:'join',roomId:room.id,userId:'B'},now+1);
assert.equal(viewRoom(state,room,now).count,2);
assert.throws(()=>run({type:'join',roomId:'214',userId:'B'}));
assert.throws(()=>run({type:'update',roomId:room.id,userId:'B',minutes:30,openToShare:false}));
run({type:'leave',roomId:room.id,userId:'A'});
assert.equal(viewRoom(state,room,now).session?.holderId,'B');
assert.equal(viewRoom(state,room,now).status,'share');
run({type:'update',roomId:room.id,userId:'B',minutes:30,openToShare:false});
assert.equal(viewRoom(state,room,now).status,'occupied');
assert.throws(()=>run({type:'join',roomId:room.id,userId:'C'}));
run({type:'leave',roomId:room.id,userId:'B'});
assert.equal(viewRoom(state,room,now).status,'free');
assert.equal(viewRoom(expire(state,now+FREE_FRESHNESS_MS),room,now+FREE_FRESHNESS_MS).status,'unknown');
const unknown=rooms.find(r=>r.id==='321')!;
assert.throws(()=>run({type:'checkIn',roomId:unknown.id,userId:'C',minutes:1,openToShare:true}));
run({type:'checkIn',roomId:unknown.id,userId:'C',minutes:1,openToShare:true,confirmedEmpty:true});
state=expire(state,now+60000);
assert.equal(viewRoom(state,unknown,now+60000).status,'unknown');
assert.ok(!state.memberships.some(m=>m.userId==='C'));
for(const minutes of [NaN,0,-1,481])assert.throws(()=>run({type:'checkIn',roomId:room.id,userId:'C',minutes,openToShare:true}));
const tiny=rooms.find(r=>r.id==='118')!;
run({type:'checkIn',roomId:tiny.id,userId:'D',minutes:60,openToShare:true});
run({type:'join',roomId:tiny.id,userId:'E'});
assert.throws(()=>run({type:'join',roomId:tiny.id,userId:'F'}));
assert.equal(viewRoom(state,tiny,now).count,2);
console.log('PASS: check-in, collision rejection, join, single active membership, holder permissions and transfer, privacy status, last leave, free freshness, unknown confirmation, expiration, duration validation, capacity.');
